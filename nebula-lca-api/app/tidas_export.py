def _repair_target_for_unit_group(graph_json: dict, unit_group: str) -> dict:
    target = {"unit_group": unit_group, "repair_target": "unit_group"}
    needle = str(unit_group or "").strip().lower()
    for node in graph_json.get("nodes", []) or []:
        if not isinstance(node, dict):
            continue
        for port in (node.get("inputs") or []) + (node.get("outputs") or []):
            current = str(port.get("unitGroup") or port.get("unit_group") or "").strip().lower()
            if current == needle:
                target.update({
                    "node_id": node.get("id"),
                    "process_uuid": node.get("process_uuid"),
                    "port_id": port.get("id"),
                    "flow_uuid": port.get("flowUuid") or port.get("flow_uuid"),
                })
                return target
    return target


def _repair_target_for_flow_uuid(graph_json: dict, flow_uuid: str) -> dict:
    target = {"flow_uuid": flow_uuid, "repair_target": "flow"}
    needle = str(flow_uuid or "").strip().lower()
    for node in graph_json.get("nodes", []) or []:
        if not isinstance(node, dict):
            continue
        for port in (node.get("inputs") or []) + (node.get("outputs") or []):
            current = str(port.get("flowUuid") or port.get("flow_uuid") or "").strip().lower()
            if current == needle:
                target.update({
                    "node_id": node.get("id"),
                    "process_uuid": node.get("process_uuid"),
                    "port_id": port.get("id"),
                    "unit_group": port.get("unitGroup") or port.get("unit_group"),
                })
                return target
    return target


def _repair_target_for_process(graph_json: dict, process_uuid: str, repair_target: str = "node") -> dict:
    target = {"process_uuid": process_uuid, "repair_target": repair_target}
    needle = str(process_uuid or "").strip()
    for node in graph_json.get("nodes", []) or []:
        if not isinstance(node, dict):
            continue
        if str(node.get("process_uuid") or node.get("id") or "").strip() == needle:
            target["node_id"] = node.get("id")
            return target
    return target


def _enrich_readiness_issue_targets(graph_json: dict, issues: list[dict]) -> None:
    for issue in issues:
        details = issue.setdefault("details", {})
        if not isinstance(details, dict):
            continue
        context = issue.get("context")
        lookup = {**context, **details} if isinstance(context, dict) else details
        code = str(issue.get("code") or "")
        category = str(issue.get("category") or "")
        if code in {"MISSING_FLOWS", "missing_flow"}:
            details.setdefault("repair_target", "flow")
            missing = lookup.get("missing_flow_uuids")
            if isinstance(missing, list) and missing:
                details.update(_repair_target_for_flow_uuid(graph_json, str(missing[0])))
                details["missing_flow_uuids"] = missing
        elif (
            category == "tidas_placeholder"
            and "missing geography" in str(issue.get("message") or "").lower()
            and lookup.get("process_uuid")
        ):
            details.update(_repair_target_for_process(graph_json, str(lookup.get("process_uuid")), "process_metadata"))
        elif code in {"missing_tiangong_field"} and "geography" in str(issue.get("message") or "").lower():
            details.setdefault("repair_target", "project_settings")
        elif (
            category == "allocation"
            and "using first product output as reference" in str(issue.get("message") or "").lower()
            and lookup.get("process_uuid")
        ):
            details.update(_repair_target_for_process(graph_json, str(lookup.get("process_uuid")), "process_metadata"))
        elif category == "allocation" or code == "manual_allocation_required":
            process_uuid = str(lookup.get("process_uuid") or "")
            if process_uuid:
                details.update(_repair_target_for_process(graph_json, process_uuid, "allocation"))
            else:
                details.setdefault("repair_target", "allocation")
        elif code == "unsupported_unit_group" and lookup.get("unit_group"):
            details.update(_repair_target_for_unit_group(graph_json, str(lookup.get("unit_group"))))
        elif lookup.get("flow_uuid"):
            details.update(_repair_target_for_flow_uuid(graph_json, str(lookup.get("flow_uuid"))))
        elif lookup.get("process_uuid") or lookup.get("node_id"):
            details.setdefault("repair_target", "node")


def _identify_product_outputs(
    outputs: list,
    flow_type_map: dict[str, str] | None = None,
) -> list[dict]:
    """Identify product outputs from a process node's outputs.

    A product output is:
    - isProduct=True, OR
    - flow_type is "Product flow" or "waste_flow" (looked up by flowUuid)

    Args:
        outputs: List of output ports
        flow_type_map: Optional dict mapping flow_uuid -> flow_type

    Returns list of product output ports with their flow info.
    """
    product_outputs = []
    for port in outputs:
        if not isinstance(port, dict):
            continue

        # Check isProduct flag
        is_product = bool(port.get("isProduct", False))

        # Also check flow type from flowUuid lookup
        if not is_product and flow_type_map:
            flow_uuid = port.get("flowUuid")
            if flow_uuid:
                flow_type = flow_type_map.get(flow_uuid, "")
                is_product = flow_type in ("Product flow", "waste_flow")

        if is_product:
            product_outputs.append(port)

    return product_outputs


def _select_reference_flow(
    product_outputs: list[dict],
    process_uuid: str,
    model: Model | None,
    report: ExportReport,
    reference_product_flow_uuid: str | None = None,
    reference_product_name: str | None = None,
) -> tuple[dict | None, str | None]:
    """Select the reference (quantitative reference) flow for a process.

    Priority:
    1. User-specified reference_product (from Model)
    2. Single product output (automatic, allocation=1.0)
    3. Multi-product: choose first product output as fallback

    Returns:
        Tuple of (reference_port, reference_flow_uuid)
    """
    if not product_outputs:
        return None, None

    # Single product output - automatic reference
    if len(product_outputs) == 1:
        ref_port = product_outputs[0]
        ref_flow_uuid = ref_port.get("flowUuid")
        report.reference_flow_by_process[process_uuid] = ref_flow_uuid
        return ref_port, ref_flow_uuid

    # Multi-product process
    report.multi_product_process_count += 1

    explicit_uuid = str(reference_product_flow_uuid or "").strip()
    explicit_name = str(reference_product_name or "").strip()
    if explicit_uuid or explicit_name:
        for port in product_outputs:
            flow_uuid = str(port.get("flowUuid") or "").strip()
            port_id = str(port.get("id") or "").strip()
            port_name = str(port.get("name") or "").strip()
            if explicit_uuid and explicit_uuid in {flow_uuid, port_id}:
                ref_port = port
                ref_flow_uuid = port.get("flowUuid")
                report.reference_flow_by_process[process_uuid] = ref_flow_uuid
                return ref_port, ref_flow_uuid
            if explicit_name and port_name == explicit_name:
                ref_port = port
                ref_flow_uuid = port.get("flowUuid")
                report.reference_flow_by_process[process_uuid] = ref_flow_uuid
                return ref_port, ref_flow_uuid

    # Try to match model's reference_product
    if model and model.reference_product:
        for port in product_outputs:
            flow_uuid = port.get("flowUuid")
            # Match by flow UUID or flow name
            if flow_uuid == model.reference_product or port.get("name") == model.reference_product:
                ref_port = port
                ref_flow_uuid = flow_uuid
                report.reference_flow_by_process[process_uuid] = ref_flow_uuid
                return ref_port, ref_flow_uuid

    # Fallback: use first product output
    ref_port = product_outputs[0]
    ref_flow_uuid = ref_port.get("flowUuid")
    report.reference_flow_by_process[process_uuid] = ref_flow_uuid

    # Warn that we're using fallback
    report.add_warning(
        "allocation",
        f"Multi-product process {process_uuid}: using first product output as reference (no explicit reference_product specified)",
        {"process_uuid": process_uuid, "reference_flow_uuid": ref_flow_uuid},
    )

    return ref_port, ref_flow_uuid


def _calculate_allocation_factors(
    product_outputs: list[dict],
    reference_port: dict | None,
    process_uuid: str,
    report: ExportReport,
    db: Session | None = None,
) -> dict[str, float] | None:
    """Calculate allocation factors for multi-product process outputs.

    Allocation is based on physical relationships (output quantities) when products
    share the same unit group. For different unit groups, manual allocation is required.

    Args:
        product_outputs: List of product output ports
        reference_port: Selected reference flow port
        process_uuid: Process UUID for reporting
        report: ExportReport for warnings
        db: Optional DB session for unit conversion

    Returns:
        Dict mapping port_id -> allocation_factor (0.0 to 1.0)
    """
    unit_factor_by_group_and_name: dict[tuple[str, str], float] | None = None
    if db is not None:
        try:
            unit_factor_by_group_and_name = {
                (str(row.unit_group), str(row.unit_name)): float(row.factor_to_reference)
                for row in db.query(UnitDefinition).all()
            }
        except Exception:
            unit_factor_by_group_and_name = None

    result = calculate_product_allocation(
        product_outputs,
        process_uuid=process_uuid,
        unit_factor_by_group_and_name=unit_factor_by_group_and_name,
    )
    for warning in result.warnings:
        report.add_warning("allocation", warning.message, warning.context)
    if result.manual_required and process_uuid not in report.manual_allocation_required_processes:
        report.manual_allocation_required_processes.append(process_uuid)
    return result.factors


