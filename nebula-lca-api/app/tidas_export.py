def export_bundle(
    db: Session,
    project_id: str,
    version: int | None = None,
    display_lang: str = "zh",
    bundle_mode: str | None = None,
) -> tuple[bytes, ExportReport]:
    """Export project to TIDAS bundle ZIP.

    Runs readiness check first; raises ``ExportError`` if blocking
    issues are found.  On success, reuses the same ZIP-build logic.

    Args:
        db: Database session
        project_id: Project/model ID
        version: Optional version number (None = latest)
        display_lang: Display language preference (zh/en)

    Returns:
        Tuple of (ZIP bytes, export report)

    Raises:
        ExportError: If validation fails
    """
    report = ExportReport()
    mode = _normalise_bundle_mode(bundle_mode)

    # ── Readiness check (short-circuit if blocking) ────────────────────
    readiness = build_tidas_readiness(db, project_id, version, mode)
    if readiness["blocking"]:
        raise ExportError(readiness["blocking"][0]["message"])

    # ── Re-fetch model and version for ZIP build ───────────────────────
    model = db.get(Model, project_id)
    if model is None:
        raise ExportError(f"Project not found: {project_id}")

    model_version = _get_model_version(db, project_id, version)
    if model_version is None:
        version_info = f" version {version}" if version else ""
        raise ExportError(f"No model version found for project {project_id}{version_info}")

    graph_json = model_version.hybrid_graph_json
    if not graph_json:
        raise ExportError(f"Empty graph for project {project_id}")

    # ── Extract graph data ─────────────────────────────────────────────
    flow_uuids, process_uuids = _extract_graph_data(graph_json)

    # ── Validate flows ─────────────────────────────────────────────────
    missing_flows: list[str] = []
    for flow_uuid in flow_uuids:
        flow_record = db.get(FlowRecord, flow_uuid)
        if flow_record is None:
            missing_flows.append(flow_uuid)
            report.add_error(f"Missing flow: {flow_uuid}")

    if missing_flows:
        raise ExportError(f"Cannot export: {len(missing_flows)} flow(s) not found in database")

    bundle_plan = _build_bundle_export_plan(db, flow_uuids, process_uuids, mode)
    if bundle_plan.blocking:
        raise ExportError(bundle_plan.blocking[0]["message"])

    # ── Build flow type map ────────────────────────────────────────────
    flow_type_map = _build_flow_type_map(db, flow_uuids)

    # ── Build ZIP in memory ────────────────────────────────────────────
    zip_buffer = io.BytesIO()

    # Self-contained exports bundle reference datasets; platform-light exports
    # leave official references for Tiangong to resolve by UUID/version.
    ref_uuids_by_type: dict[str, set[str]] = {}  # "source" / "contact" -> set of uuids
    if mode == TIDAS_BUNDLE_MODE_SELF_CONTAINED:
        for desc_key in _BUNDLED_REFERENCE_DESCRIPTIONS:
            ref_type, ref_uuid = desc_key
            ref_uuids_by_type.setdefault(ref_type, set()).add(ref_uuid)
    bundled_flow_properties: dict[str, dict[str, Any]] = {}
    bundled_unit_groups: dict[str, dict[str, Any]] = {}

    with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        dataset_version = TIDAS_DEFAULT_DATASET_VERSION

        # Build and write flow data as one dataset file per flow.
        flow_uuid_list: list[str] = []
        for flow_uuid in sorted(bundle_plan.included_flow_uuids):
            flow_data = _build_flow_data(db, flow_uuid, report)
            if flow_data:
                flow_uuid_list.append(flow_uuid)
                flow_record = db.get(FlowRecord, flow_uuid)
                if flow_record is not None and mode == TIDAS_BUNDLE_MODE_SELF_CONTAINED:
                    bundle_info = get_tidas_flow_property_bundle_info(flow_record.unit_group)
                    if bundle_info:
                        reference = bundle_info.get("reference") or {}
                        ref_uuid = str(reference.get("@refObjectId") or "").strip()
                        unit_group = bundle_info.get("unit_group")
                        if ref_uuid and isinstance(unit_group, dict):
                            bundled_flow_properties[ref_uuid] = bundle_info
                            unit_group_uuid = str(unit_group.get("uuid") or "").strip()
                            if unit_group_uuid:
                                bundled_unit_groups[unit_group_uuid] = unit_group
                zf.writestr(
                    f"flows/{flow_uuid}_{dataset_version}.json",
                    json.dumps(flow_data, ensure_ascii=False, indent=2),
                )

        # Build and write process data as one dataset file per process.
        process_uuid_list: list[str] = []
        for process_uuid in sorted(bundle_plan.included_process_uuids):
            process_data = _build_process_data(db, process_uuid, graph_json, report, model, flow_type_map)
            if process_data:
                process_uuid_list.append(process_uuid)
                zf.writestr(
                    f"processes/{_tidas_uuid(process_uuid)}_{dataset_version}.json",
                    json.dumps(process_data, ensure_ascii=False, indent=2),
                )

        # Build and write model data
        model_data = _build_model_data(db, model, graph_json, report)
        zf.writestr(
            f"lifecyclemodels/{project_id}_{dataset_version}.json",
            json.dumps(model_data, ensure_ascii=False, indent=2),
        )

        # ── Write bundled reference datasets ───────────────────────────
        reference_files: list[str] = []
        for ref_type, ref_uuids in sorted(ref_uuids_by_type.items()):
            for ref_uuid in sorted(ref_uuids):
                desc_key = (ref_type, ref_uuid)
                desc_en, desc_zh = _BUNDLED_REFERENCE_DESCRIPTIONS[desc_key]
                file_path = f"{ref_type}s/{ref_uuid}_{dataset_version}.json"
                reference_files.append(file_path)

                if ref_type == "source":
                    dataset = build_tidas_source_dataset(ref_uuid, desc_en, desc_zh)
                else:
                    dataset = build_tidas_contact_dataset(ref_uuid, desc_en, desc_zh)

                zf.writestr(
                    file_path,
                    json.dumps(dataset, ensure_ascii=False, indent=2),
                )

        for unit_group_uuid, unit_group in sorted(bundled_unit_groups.items()):
            file_path = f"unitgroups/{unit_group_uuid}_{dataset_version}.json"
            reference_files.append(file_path)
            zf.writestr(
                file_path,
                json.dumps(build_tidas_unit_group_dataset(unit_group), ensure_ascii=False, indent=2),
            )

        for flow_property_uuid, bundle_info in sorted(bundled_flow_properties.items()):
            reference = bundle_info.get("reference") or {}
            unit_group = bundle_info.get("unit_group") or {}
            file_path = f"flowproperties/{flow_property_uuid}_{dataset_version}.json"
            reference_files.append(file_path)
            zf.writestr(
                file_path,
                json.dumps(
                    build_tidas_flow_property_dataset(
                        flow_property_uuid,
                        str(reference.get("@uri") or f"../flowproperties/{flow_property_uuid}.xml"),
                        str(reference.get("@version") or "01.00.000"),
                        unit_group,
                        reference.get("common:shortDescription"),
                    ),
                    ensure_ascii=False,
                    indent=2,
                ),
            )

        # Build and write manifest
        manifest = _build_manifest(
            project_id,
            flow_uuid_list,
            process_uuid_list,
            reference_files,
        )
        zf.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))

        # Write export report
        export_report_data = report.to_dict()
        export_report_data["project_id"] = project_id
        export_report_data["project_name"] = model.name
        export_report_data["version"] = model_version.version
        export_report_data["display_lang"] = display_lang
        export_report_data["bundle_mode"] = mode
        export_report_data["included_flow_count"] = bundle_plan.included_flow_count
        export_report_data["referenced_flow_count"] = bundle_plan.referenced_flow_count
        export_report_data["included_flow_uuids"] = sorted(bundle_plan.included_flow_uuids)
        export_report_data["referenced_flow_uuids"] = sorted(bundle_plan.referenced_flow_uuids)
        export_report_data["included_process_count"] = bundle_plan.included_process_count
        export_report_data["referenced_process_count"] = bundle_plan.referenced_process_count
        export_report_data["included_process_uuids"] = sorted(bundle_plan.included_process_uuids)
        export_report_data["referenced_process_uuids"] = sorted(bundle_plan.referenced_process_uuids)
        export_report_data["reference_dataset_count"] = len(reference_files)
        export_report_data["reference_dataset_paths"] = reference_files
        zf.writestr("export_report.json", json.dumps(export_report_data, ensure_ascii=False, indent=2))

    zip_buffer.seek(0)
    return zip_buffer.getvalue(), report
