def _normalise_bundle_mode(bundle_mode: str | None) -> str:
    mode = (bundle_mode or TIDAS_BUNDLE_MODE_REFERENCE_HYBRID).strip()
    if mode not in TIDAS_BUNDLE_MODES:
        return TIDAS_BUNDLE_MODE_REFERENCE_HYBRID
    return mode


def _is_tidas_reference_flow(flow_record: FlowRecord) -> bool:
    return classify_flow_source(flow_record.source, bool(flow_record.is_custom)) == SOURCE_SPACE_TIANGONG


def _is_tidas_reference_process(ref_process: ReferenceProcess | None) -> bool:
    if ref_process is None:
        return False
    return classify_process_source(ref_process.source_file, ref_process.import_mode) == SOURCE_SPACE_TIANGONG


def _build_bundle_export_plan(
    db: Session,
    flow_uuids: set[str],
    process_uuids: set[str] | None = None,
    bundle_mode: str | None = None,
) -> _BundleExportPlan:
    mode = _normalise_bundle_mode(bundle_mode)
    plan = _BundleExportPlan(bundle_mode=mode)

    for flow_uuid in sorted(flow_uuids):
        flow_record = db.get(FlowRecord, flow_uuid)
        if flow_record is None:
            continue

        if mode == TIDAS_BUNDLE_MODE_SELF_CONTAINED:
            if not get_tidas_flow_property_reference(flow_record.unit_group):
                plan.blocking.append({
                    "code": "TIDAS_FLOW_PROPERTY_MAPPING_MISSING",
                    "message": f"Flow {flow_uuid} unit group is not mapped to a TIDAS flow property.",
                    "details": {
                        "flow_uuid": flow_uuid,
                        "unit_group": flow_record.unit_group,
                        "repair_target": "unit_group",
                    },
                })
                continue
            plan.included_flow_uuids.add(flow_uuid)
            continue

        if _is_tidas_reference_flow(flow_record):
            plan.referenced_flow_uuids.add(flow_uuid)
            continue

        if not bool(flow_record.tidas_compatible):
            plan.blocking.append({
                "code": "TIDAS_CUSTOM_FLOW_NOT_COMPATIBLE",
                "message": (
                    f"Flow {flow_uuid} is not a Tiangong platform reference flow and is not marked "
                    "TIDAS-compatible."
                ),
                "details": {
                    "flow_uuid": flow_uuid,
                    "source": flow_record.source,
                    "is_custom": bool(flow_record.is_custom),
                    "bundle_mode": mode,
                    "repair_target": "flow_source",
                },
            })
            continue

        unit_group = flow_record.tidas_unit_group or flow_record.unit_group
        if not get_tidas_flow_property_reference(unit_group):
            plan.blocking.append({
                "code": "TIDAS_FLOW_PROPERTY_MAPPING_MISSING",
                "message": f"Flow {flow_uuid} unit group is not mapped to a TIDAS flow property.",
                "details": {
                    "flow_uuid": flow_uuid,
                    "unit_group": unit_group,
                    "repair_target": "unit_group",
                },
            })
            continue

        plan.included_flow_uuids.add(flow_uuid)

    for process_uuid in sorted(process_uuids or set()):
        ref_process = db.get(ReferenceProcess, process_uuid)
        if mode == TIDAS_BUNDLE_MODE_SELF_CONTAINED:
            plan.included_process_uuids.add(process_uuid)
        elif _is_tidas_reference_process(ref_process):
            plan.referenced_process_uuids.add(process_uuid)
        else:
            plan.included_process_uuids.add(process_uuid)

    return plan


def _extract_graph_data(graph_json: dict) -> tuple[set[str], set[str]]:
    """Extract unique flow_uuids and process_uuids from graph.

    Returns:
        Tuple of (flow_uuids, process_uuids)
    """
    flow_uuids: set[str] = set()
    process_uuids: set[str] = set()

    nodes = graph_json.get("nodes", [])
    for node in nodes:
        if not isinstance(node, dict):
            continue

        # Use process_uuid from node, fallback to id only if process_uuid missing
        process_uuid = node.get("process_uuid") or node.get("id")
        if process_uuid:
            process_uuids.add(str(process_uuid))

        # Collect flow UUIDs from ports
        for bucket in ("inputs", "outputs"):
            ports = node.get(bucket, [])
            for port in ports:
                if not isinstance(port, dict):
                    continue
                flow_uuid = port.get("flowUuid")
                if flow_uuid:
                    flow_uuids.add(str(flow_uuid))

    # Also check exchanges if present
    exchanges = graph_json.get("exchanges", [])
    for exchange in exchanges:
        if not isinstance(exchange, dict):
            continue
        flow_uuid = exchange.get("flowUuid")
        if flow_uuid:
            flow_uuids.add(str(flow_uuid))

    return flow_uuids, process_uuids


def _read_target_product_config(graph_json: dict) -> dict[str, str]:
    metadata = graph_json.get("metadata") if isinstance(graph_json, dict) else {}
    if not isinstance(metadata, dict):
        return {}
    preferences = metadata.get("project_preferences")
    if not isinstance(preferences, dict):
        return {}
    target_product = preferences.get("target_product")
    if not isinstance(target_product, dict):
        return {}

    process_uuid = str(
        target_product.get("process_uuid")
        or target_product.get("processUuid")
        or ""
    ).strip()
    flow_uuid = str(
        target_product.get("flow_uuid")
        or target_product.get("flowUuid")
        or ""
    ).strip()
    product_key = str(
        target_product.get("product_key")
        or target_product.get("productKey")
        or ""
    ).strip()
    if (not process_uuid or not flow_uuid) and "::" in product_key:
        legacy_process_uuid, legacy_flow_uuid = product_key.split("::", 1)
        process_uuid = process_uuid or legacy_process_uuid.strip()
        flow_uuid = flow_uuid or legacy_flow_uuid.strip()

    result: dict[str, str] = {}
    if process_uuid:
        result["process_uuid"] = process_uuid
    if flow_uuid:
        result["flow_uuid"] = flow_uuid
    return result


def _derive_model_reference_product(model: Model, graph_json: dict) -> str | None:
    explicit = str(model.reference_product or "").strip()
    if explicit:
        return explicit

    target_product = _read_target_product_config(graph_json)
    target_process_uuid = target_product.get("process_uuid")
    target_flow_uuid = target_product.get("flow_uuid")

    first_product_name: str | None = None
    for node in graph_json.get("nodes", []) or []:
        if not isinstance(node, dict):
            continue
        process_uuid = str(node.get("process_uuid") or node.get("id") or "").strip()
        node_reference_flow_uuid = str(node.get("reference_product_flow_uuid") or "").strip()
        node_reference_product = str(node.get("reference_product") or "").strip()
        if (
            target_flow_uuid
            and node_reference_flow_uuid == target_flow_uuid
            and (not target_process_uuid or process_uuid == target_process_uuid)
            and node_reference_product
        ):
            return node_reference_product

        for port in node.get("outputs", []) or []:
            if not isinstance(port, dict):
                continue
            flow_uuid = str(port.get("flowUuid") or port.get("flow_uuid") or "").strip()
            port_name = str(port.get("name") or port.get("product_name") or "").strip()
            is_product = bool(port.get("isProduct")) or str(port.get("type") or "").lower() == "technosphere"
            if not port_name or not is_product:
                continue
            if first_product_name is None:
                first_product_name = port_name
            if (
                target_flow_uuid
                and flow_uuid == target_flow_uuid
                and (not target_process_uuid or process_uuid == target_process_uuid)
            ):
                return port_name

    return first_product_name


