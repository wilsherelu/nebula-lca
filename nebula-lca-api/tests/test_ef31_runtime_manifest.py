    def test_manifest_contains_required_fields(self, tmp_path: Path) -> None:
        """generate_ef31_runtime_csvs produces manifest.json with all required keys."""
        from app.services.ef31_runtime_csv import generate_ef31_runtime_csvs

        job_dir = tmp_path / "job_001"
        job_dir.mkdir()
        self._write_job_artifacts(tmp_path, job_dir)
        output_root = tmp_path / "runtime"
        output_root.mkdir()

        result = generate_ef31_runtime_csvs(
            job_id="job_001",
            output_root=output_root,
            _job_dir_override=job_dir,
        )

        # Verify return dict has expected keys
        assert "flows_count" in result
        assert "indicators_count" in result
        assert "factors_count" in result
        assert "cf_matched" in result
        assert "cf_unmatched" in result
        assert "cf_ambiguous" in result

        # Verify manifest.json on disk (written to output_root/{job_id}/)
        manifest_path = output_root / "job_001" / "manifest.json"
        assert manifest_path.exists()
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        assert manifest["job_id"] == "job_001"
        assert "flows_count" in manifest
        assert "indicators_count" in manifest
        assert "factors_count" in manifest
        assert "cf_matched" in manifest
        assert "cf_unmatched" in manifest
        assert "cf_ambiguous" in manifest

    def test_manifest_preserves_cf_counts(self, tmp_path: Path) -> None:
        """CF matched/unmatched counts should be preserved in manifest."""
