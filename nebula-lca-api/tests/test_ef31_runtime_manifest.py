"""Regression tests for EF3.1 runtime artifact manifest and integrity.

Covers:
1. generate_ef31_runtime_csvs() produces manifest.json with all required fields.
2. active_manifest.json points to the runtime generated by the correct import job.
3. The manifest preserves cf_matched / cf_unmatched / cf_ambiguous counts.
"""

