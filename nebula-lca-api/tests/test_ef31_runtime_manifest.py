    def test_active_manifest_points_to_correct_runtime(self, tmp_path: Path) -> None:
        """active_manifest.json should point to the runtime generated by the import job."""
        from app.services.ef31_runtime_csv import generate_ef31_runtime_csvs

        job_dir = tmp_path / "job_003"
        job_dir.mkdir()
        self._write_job_artifacts(tmp_path, job_dir)
        output_root = tmp_path / "runtime_003"
        output_root.mkdir()

        generate_ef31_runtime_csvs(
            job_id="job_003",
            output_root=output_root,
            _job_dir_override=job_dir,
        )

        active_manifest_path = output_root / "active_manifest.json"
        assert active_manifest_path.exists()
